-- Cities come from a fixed list, so their ids are given, not generated.
CREATE TABLE cities (
    id                    integer PRIMARY KEY,
    code                  text    NOT NULL UNIQUE,
    name                  text    NOT NULL,
    persian_name          text    NOT NULL,
    province_name         text    NOT NULL,
    province_persian_name text    NOT NULL,
    is_capital            boolean NOT NULL DEFAULT false,
    sort_order            integer NOT NULL DEFAULT 0
);

-- Alternate spellings of a city, used for autocomplete.
CREATE TABLE search_expressions (
    id         bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id    integer NOT NULL REFERENCES cities (id) ON DELETE CASCADE,
    expression text    NOT NULL
);
CREATE INDEX search_expressions_city_id_idx ON search_expressions (city_id);
-- text_pattern_ops makes "starts with" searches (LIKE 'teh%') use the index.
CREATE INDEX search_expressions_prefix_idx ON search_expressions (lower(expression) text_pattern_ops);

-- A bus station. One city can have several.
CREATE TABLE terminals (
    id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    city_id      integer NOT NULL REFERENCES cities (id),
    code         text    NOT NULL UNIQUE,
    name         text    NOT NULL,
    persian_name text    NOT NULL
);
CREATE INDEX terminals_city_id_idx ON terminals (city_id);

CREATE TABLE companies (
    id           integer     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         text        NOT NULL UNIQUE,
    name         text        NOT NULL,
    persian_name text        NOT NULL,
    logo         text        NOT NULL DEFAULT '',
    url          text        NOT NULL DEFAULT '',
    is_active    boolean     NOT NULL DEFAULT true,
    created_at   timestamptz NOT NULL DEFAULT now()
);

-- "code" names the seat layout the website draws, for example VIP_25_1.
CREATE TABLE bus_types (
    id         integer  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       text     NOT NULL UNIQUE,
    seat_count smallint NOT NULL CHECK (seat_count > 0),
    is_vip     boolean  NOT NULL DEFAULT true
);

-- One bus trip on one day. Date and time are local Iranian time.
CREATE TABLE services (
    id                      bigint        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id              integer       NOT NULL REFERENCES companies (id),
    bus_type_id             integer       NOT NULL REFERENCES bus_types (id),
    origin_terminal_id      integer       NOT NULL REFERENCES terminals (id),
    destination_terminal_id integer       NOT NULL REFERENCES terminals (id),
    bus_name                text          NOT NULL,
    price                   bigint        NOT NULL CHECK (price >= 0),
    discount_percentage     numeric(5, 2) NOT NULL DEFAULT 0 CHECK (discount_percentage BETWEEN 0 AND 100),
    departure_date          date          NOT NULL,
    departure_time          time          NOT NULL,
    description             text          NOT NULL DEFAULT '',
    brief_description       text,
    created_at              timestamptz   NOT NULL DEFAULT now(),
    updated_at              timestamptz   NOT NULL DEFAULT now(),
    CHECK (origin_terminal_id <> destination_terminal_id)
);
-- The search looks up trips by day and by the two terminals.
CREATE INDEX services_search_idx ON services (departure_date, origin_terminal_id, destination_terminal_id);

-- Stops between origin and destination.
CREATE TABLE midway_cities (
    service_id bigint   NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    city_id    integer  NOT NULL REFERENCES cities (id),
    stop_order smallint NOT NULL DEFAULT 1,
    PRIMARY KEY (service_id, city_id)
);

-- Every seat of every trip has a row. A seat number cannot repeat inside a trip.
CREATE TABLE seats (
    id          bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id  bigint   NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    seat_number smallint NOT NULL CHECK (seat_number > 0),
    for_sale    boolean  NOT NULL DEFAULT true,
    UNIQUE (service_id, seat_number)
);

-- "Cancel at least N hours before departure and lose X percent."
CREATE TABLE refund_rules (
    id                         bigint   GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    service_id                 bigint   NOT NULL REFERENCES services (id) ON DELETE CASCADE,
    min_hours_before_departure integer  NOT NULL CHECK (min_hours_before_departure >= 0),
    penalty_percent            smallint NOT NULL CHECK (penalty_percent BETWEEN 0 AND 100),
    UNIQUE (service_id, min_hours_before_departure)
);

CREATE TABLE users (
    id            bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      text        NOT NULL UNIQUE,
    first_name    text        NOT NULL,
    last_name     text        NOT NULL,
    password_hash text        NOT NULL,
    phone_number  text        NOT NULL,
    email         text        NOT NULL UNIQUE,
    national_code text        NOT NULL UNIQUE,
    birth_date    date        NOT NULL,
    gender        char(1)     NOT NULL CHECK (gender IN ('M', 'F')),
    role          text        NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'admin')),
    is_active     boolean     NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tickets (
    id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        text        NOT NULL UNIQUE,
    service_id  bigint      NOT NULL REFERENCES services (id),
    user_id     bigint      NOT NULL REFERENCES users (id),
    status      text        NOT NULL DEFAULT 'reserved' CHECK (status IN ('reserved', 'paid', 'cancelled')),
    reserved_at timestamptz NOT NULL DEFAULT now(),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX tickets_service_id_idx ON tickets (service_id);
CREATE INDEX tickets_user_id_idx ON tickets (user_id);

-- One person in one seat. UNIQUE (seat_id) is what stops a seat being sold twice.
CREATE TABLE passengers (
    id            bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_id     bigint  NOT NULL REFERENCES tickets (id) ON DELETE CASCADE,
    seat_id       bigint  NOT NULL UNIQUE REFERENCES seats (id),
    first_name    text    NOT NULL,
    last_name     text    NOT NULL,
    gender        char(1) NOT NULL CHECK (gender IN ('M', 'F')),
    national_code text    NOT NULL,
    birth_date    date    NOT NULL
);
CREATE INDEX passengers_ticket_id_idx ON passengers (ticket_id);

